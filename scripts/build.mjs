/* Build: node scripts/build.mjs <outDir> <prod|preview>
   1. Render every page to <outDir>/<route>/index.html
   2. Bundle client JS (GSAP, Lenis, app code) and CSS with esbuild
   3. Copy fonts and favicon, write config.js, sitemap.xml and robots.txt */
import fs from "node:fs";
import path from "node:path";
import { build } from "esbuild";
import { ROOT, OUT, MODE, PAGE_COUNT, R, U, catUrl, dishUrl } from "../src/lib/site.mjs";
import { CATS, ITEMS } from "../src/data/menu.mjs";
import { buildHome } from "../src/pages/home.mjs";
import { buildMenu } from "../src/pages/menu.mjs";
import { buildItems } from "../src/pages/item.mjs";
import { buildInfoPages } from "../src/pages/info.mjs";
import { buildOrdering } from "../src/pages/ordering.mjs";
import { buildAccount } from "../src/pages/account.mjs";
import { buildSystem } from "../src/pages/system.mjs";

fs.rmSync(OUT, { recursive: true, force: true });
fs.mkdirSync(path.join(OUT, "assets/fonts"), { recursive: true });

buildHome(); buildMenu(); buildItems(); buildInfoPages(); buildOrdering(); buildAccount(); buildSystem();

const A = path.join(OUT, "assets");
await build({ entryPoints: [path.join(ROOT, "src/client/main.js")], bundle: true, minify: true, format: "iife", target: "es2019", outfile: path.join(A, "app.js"), legalComments: "none", logLevel: "warning" });
await build({ entryPoints: [path.join(ROOT, "src/styles/main.css")], bundle: true, minify: true, outfile: path.join(A, "styles.css"), external: ["fonts/*"], logLevel: "warning" });
for (const f of fs.readdirSync(path.join(ROOT, "public/fonts"))) fs.copyFileSync(path.join(ROOT, "public/fonts", f), path.join(A, "fonts", f));
fs.copyFileSync(path.join(ROOT, "public/favicon.svg"), path.join(A, "favicon.svg"));

/* Runtime settings. ZG_API_BASE is the only environment variable. Empty means no backend: forms never pretend to send. */
const cfg = { API_BASE: process.env.ZG_API_BASE || "", TOAST_URL: R.links.toast, EMAIL: R.email, PHONE: R.phone, TEL: R.tel, NAME: R.name };
fs.writeFileSync(path.join(A, "config.js"), `/* Generated by scripts/build.mjs from src/data/restaurant.mjs */\nwindow.ZG_CONFIG=${JSON.stringify(cfg)};\n`);

const indexable = [U.home, U.menu, U.deals, U.about, U.catering, U.parties, U.reservations, U.contact, U.gallery, U.privacy, U.terms, U.access, U.cookies, ...CATS.map(catUrl), ...ITEMS.map(dishUrl)];
fs.writeFileSync(path.join(OUT, "sitemap.xml"), `<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n${indexable.map((u) => `<url><loc>${R.site}${u}</loc></url>`).join("\n")}\n</urlset>\n`);
fs.writeFileSync(path.join(OUT, "robots.txt"), `User-agent: *\nAllow: /\n${[U.cart, U.checkout, U.confirm, U.login, U.signup, U.forgot, U.account, U.error].map((u) => `Disallow: ${u}`).join("\n")}\nSitemap: ${R.site}/sitemap.xml\n`);
console.log(`built ${PAGE_COUNT.n} pages (${indexable.length} in sitemap) -> ${path.relative(ROOT, OUT)} [${MODE}]`);
